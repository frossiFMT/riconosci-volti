import asyncio, subprocess, sys, time, json, os
QUI=os.path.dirname(os.path.abspath(__file__)); RADICE=os.path.abspath(os.path.join(QUI,'..','..')); VIDEO=os.path.join(QUI,'vacche.y4m')
CHROME=os.environ.get('CHROME','/usr/bin/google-chrome')
from playwright.async_api import async_playwright
MOCK=open(os.path.join(QUI,'fbmock.js')).read()
async def main():
    srv = subprocess.Popen([sys.executable,'-m','http.server','8778','-d',RADICE],stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL)
    await asyncio.sleep(1)
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path=CHROME, args=['--use-gl=swiftshader','--enable-unsafe-swiftshader','--use-fake-ui-for-media-stream','--use-fake-device-for-media-stream','--use-file-for-fake-video-capture='+VIDEO])
        ctx = await b.new_context(viewport={'width':390,'height':844}, permissions=['camera'])
        pg = await ctx.new_page()
        pg.on('pageerror', lambda e: print('PAGEERR', e))
        pg.on('console', lambda m: print('CONSOLE', m.text[:200]) if m.type=='error' else None)
        await pg.route('**/firebase-bundle.js', lambda r: r.fulfill(body=MOCK, content_type='application/javascript'))
        await pg.route('**/firebase-config.js', lambda r: r.fulfill(body='', content_type='application/javascript'))
        await pg.goto('http://localhost:8778/')
        await pg.wait_for_selector('#shLogin.open', timeout=30000)
        await pg.fill('#lEmail','amico@stalla.it'); await pg.fill('#lPass','sbagliata'); await pg.click('#lGo'); await asyncio.sleep(0.6)
        print('errore login:', await pg.inner_text('#lErr'))
        await pg.screenshot(path='r_login.png')
        await pg.fill('#lPass','segreta'); await pg.click('#lGo')
        await pg.wait_for_selector('#start', state='visible', timeout=120000)
        await pg.click('#start'); t0=time.time(); await asyncio.sleep(0.5)
        await pg.click('#bNew')
        await pg.wait_for_selector('#shCow.open', timeout=60000)
        print('dorso acquisito in %.1fs'%(time.time()-t0))
        await pg.fill('#fMat','112'); await pg.fill('#fName','Bella'); await pg.click('#cSave')
        await pg.wait_for_selector('#shMuzAsk.open', timeout=5000); await pg.screenshot(path='r_muzask.png')
        await pg.click('#mGo'); await asyncio.sleep(1)
        for i in range(3): await pg.click('#shutter'); await asyncio.sleep(0.4)
        await pg.screenshot(path='r_muz.png')
        await pg.click('#hudX'); await asyncio.sleep(2)
        db=await pg.evaluate("()=>{const d=window.__mockdb; return {vacche:Object.fromEntries(Object.entries(d.vacche).map(([k,v])=>[k,{matricola:v.matricola,nome:v.nome,embLen:(v.emb||'').length,nEmb:v.nEmb,nFotoDorso:v.nFotoDorso,nFotoMusello:v.nFotoMusello,thumbLen:(v.thumb||'').length,da:v.aggiornatoDa}])), foto:Object.values(d.foto).map(f=>({tipo:f.tipo,mat:f.matricola,kb:Math.round(f.jpeg.length/1024),w:f.w,h:f.h,crop:f.ritaglio,ses:f.sessione}))}}")
        print(json.dumps(db['vacche'],indent=0)); 
        from collections import Counter
        print('foto per tipo:',Counter(f['tipo'] for f in db['foto'])); print('dimensione max KB:',max(f['kb'] for f in db['foto']), 'esempio:',db['foto'][0])
        for i in range(8):
            print('%4.1fs'%(time.time()-t0), await pg.evaluate('window.__vacche.state()'), await pg.evaluate('window.__vacche.cloud()')); await asyncio.sleep(1.5)
        await pg.screenshot(path='r_ok.png')
        cnt=lambda: pg.evaluate("()=>({vacche:Object.keys(window.__mockdb.vacche), foto:Object.values(window.__mockdb.foto).map(f=>f.vacca)})")
        # foto rimasta da una vacca eliminata con la versione vecchia
        await pg.evaluate("()=>{window.__mockdb.foto['old1']={matricola:'test123',vacca:'TEST123',tipo:'dorso',jpeg:'data:image/jpeg;base64,/9j/',ordine:1,sessione:'x'}}")
        print('prima:', await cnt())
        await pg.click('#bArch'); await asyncio.sleep(0.4)
        async with pg.expect_download(timeout=60000) as dl:
            await pg.click('#aDs')
        d=await dl.value; await d.save_as('ds_prova.zip')
        import zipfile; z=zipfile.ZipFile('ds_prova.zip'); print('foto nel dataset:', sum(n.startswith('dataset') and '/foto/' in n for n in z.namelist()), '| test123 presente:', any('test123' in n for n in z.namelist()))
